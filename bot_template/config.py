# 📌 راحتیِ کار: لازم نیست حتماً «@» بذاری. هر شکلی بنویسی خودکار تمیز می‌شه:
#     beebot_studio   |   @beebot_studio   |   //beebot_studio/
#     https://splus.ir/beebot_studio   →   همه تبدیل می‌شن به @beebot_studio
# ============================================================
import re as _re


def clean_handle(value):
    """هر شکلی از آیدی/لینک کانال رو به یک هندلِ تمیزِ «@name» تبدیل می‌کنه.
    اگه مقدار خالی یا لینکِ عضویت (joingroup) باشه، دست‌نخورده برمی‌گرده."""
    raw = str(value or "").strip()
    if not raw:
        return ""
    if "joingroup" in raw or "/+" in raw:      # لینک عضویت گروه، نه هندل
        return raw
    cleaned = _re.sub(r"^https?://", "", raw, flags=_re.I)
    cleaned = _re.sub(r"^(?:www\.)?(?:splus\.ir|t\.me|telegram\.me|sapp\.ir)/", "", cleaned, flags=_re.I)
    cleaned = cleaned.strip().strip("@").strip("/").strip()
    cleaned = cleaned.strip("@/").strip()
    return ("@" + cleaned) if cleaned else ""


